use std::collections::BTreeMap;
use std::sync::LazyLock;

use super::{Context, Sequence};

pub(super) fn org_complete() -> &'static [(&'static str, &'static str)] {
    static COMPLETE: LazyLock<Vec<(&str, &str)>> = LazyLock::new(|| complete(EDITOR, ORG));
    &COMPLETE
}
pub(super) fn calendar_complete() -> &'static [(&'static str, &'static str)] {
    static COMPLETE: LazyLock<Vec<(&str, &str)>> =
        LazyLock::new(|| complete(MINIBUFFER, ORG_CALENDAR));
    &COMPLETE
}
pub(super) fn capture_complete() -> &'static [(&'static str, &'static str)] {
    static COMPLETE: LazyLock<Vec<(&str, &str)>> = LazyLock::new(|| complete(EDITOR, ORG_CAPTURE));
    &COMPLETE
}
pub(super) fn source_complete() -> &'static [(&'static str, &'static str)] {
    static COMPLETE: LazyLock<Vec<(&str, &str)>> =
        LazyLock::new(|| complete(EDITOR, ORG_SOURCE_EDIT));
    &COMPLETE
}
fn complete(
    base: &'static [(&'static str, &'static str)],
    local: &'static [(&'static str, &'static str)],
) -> Vec<(&'static str, &'static str)> {
    base.iter()
        .chain(local)
        .map(|entry| {
            let key = Sequence::parse(entry.0).expect("audited built-in sequence");
            (key, *entry)
        })
        .collect::<BTreeMap<_, _>>()
        .into_values()
        .collect()
}

pub(super) fn bindings(context: Context) -> &'static [(&'static str, &'static str)] {
    match context {
        Context::Editor => EDITOR,
        Context::Minibuffer => MINIBUFFER,
        Context::Tree => TREE,
        Context::Org => ORG,
        Context::OrgAgenda => ORG_AGENDA,
        Context::OrgCapture => ORG_CAPTURE,
        Context::OrgCalendar => ORG_CALENDAR,
        Context::OrgSourceEdit => ORG_SOURCE_EDIT,
    }
}

