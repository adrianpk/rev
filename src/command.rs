impl Command {
    /// Repetition belongs to the resolved action, independent of its chord.
    /// Prefix completions and session/prompt transitions require fresh presses.
    pub(crate) fn repeatable(self) -> bool {
        if let Self::Edit(request) = self {
            return matches!(
                request.action,
                editing::Action::DeleteForward
                    | editing::Action::DeleteBackward
                    | editing::Action::PasteAfter
                    | editing::Action::PasteBefore
                    | editing::Action::Join
            );
        }
        if let Self::Navigate(request) = self {
            return !matches!(request.target, Target::Find(_) | Target::Search(_));
        }
        if let Self::Org(command) = self {
            return command.timestamp_step()
                || command.calendar() && command != OrgCommand::CalendarSelect;
        }
        matches!(
            self,
            Self::Bookmark(BookmarkCommand::Next | BookmarkCommand::Previous)
                | Self::Newline
                | Self::InsertTab
                | Self::BackwardDeleteChar
                | Self::DeleteChar
                | Self::Motion(_)
                | Self::Scroll(_)
                | Self::History(_)
                | Self::Region(_)
                | Self::Kill(_)
                | Self::Linear(_)
                | Self::SearchForward
                | Self::SearchBackward
        )
    }
}
