use super::*;
use rev::macros::{Status, StopReason};

// Raw keys re-enter the typing policy once; generated mates never become
// captured keys. Counted open/skip and Unicode retain one undo per replay.
#[test]
fn raw_keys() {
    for profile in ["non-modal", "modal"] {
        let config = format!("editor.interaction_profile='{profile}'");
        let mut e = Editor::new(&config, "plain", "|");
        mode(&mut e, profile);
        function(&mut e.session, 3);
        e.counted("3", '(');
        e.type_key('界');
        e.counted("3", ')');
        function(&mut e.session, 4);
        e.expect("(((界)))|");
        let recorded = e.session.buffer().unwrap().stamp();
        function(&mut e.session, 4);
        e.expect("(((界)))(((界)))|");
        assert_ne!(e.session.buffer().unwrap().stamp(), recorded);
        assert_eq!(e.session.macro_status(), Status::Idle);
        assert_eq!(e.session.macro_stop(), None);
        e.session.execute(Command::History(History::Undo));
        settle(&mut e.session);
        e.expect("(((界)))|");
        e.session.execute(Command::History(History::Redo));
        settle(&mut e.session);
        // Closer skipping is navigation; redo restores the last source edit's
        // cursor, rather than creating history for those later navigation keys.
        e.expect("(((界)))(((界|)))");
    }
}

// Paste is an accepted literal step even when it contains unmatched opening
// delimiters. Replay counts repeat that payload, without pairing its characters.
#[test]
fn accepted_text() {
    let payload = "([{\"界e\u{301}\r\n";
    for profile in ["non-modal", "modal"] {
        let mut e = Editor::new(
            &format!("editor.interaction_profile='{profile}'"),
            "plain",
            "|",
        );
        mode(&mut e, profile);
        function(&mut e.session, 3);
        e.session.handle(Event::Paste(payload.into()));
        settle(&mut e.session);
        function(&mut e.session, 4);
        e.expect(&format!("{payload}|"));
        e.session
            .handle(key(KeyCode::Char('u'), KeyModifiers::CONTROL));
        e.session.handle(character('3'));
        function(&mut e.session, 4);
        e.expect(&format!("{}|", payload.repeat(4)));
        assert_eq!(e.session.macro_stop(), None);
        e.session.execute(Command::History(History::Undo));
        settle(&mut e.session);
        e.expect(&format!("{}|", payload.repeat(3)));
    }
}

// Replay uses the buffer's current automatic policy, not generated bytes from
// recording. Turning pairing off cannot leave a hidden captured closing key.
#[test]
fn current_policy() {
    let mut e = Editor::new("", "plain", "|");
    function(&mut e.session, 3);
    e.type_key('(');
    function(&mut e.session, 4);
    e.expect("(|)");
    e.session.execute(Command::Motion(Motion::BufferEnd));
    e.session.execute(Command::AutoPairMode);
    function(&mut e.session, 4);
    e.expect("()(|");
    e.session.execute(Command::History(History::Undo));
    settle(&mut e.session);
    e.expect("()|");
}

// A replay waiting for bounded qualification remains cancelable through the
// existing macro owner. No half pair, queued source edit or retry survives C-g.
#[test]
fn pending_cancel() {
    let mut e = Editor::new("", "plain", "|");
    function(&mut e.session, 3);
    e.type_key('(');
    function(&mut e.session, 4);
    let source = " ".repeat(200_000);
    e.session.replace(0..2, &source).unwrap();
    e.session.execute(Command::Motion(Motion::BufferEnd));
    settle(&mut e.session);
    let stamp = e.session.buffer().unwrap().stamp();
    let point = e.session.view().point;
    e.session.handle(key(KeyCode::F(4), KeyModifiers::NONE));
    assert_eq!(e.session.macro_status(), Status::Playing);
    e.session.expire_input(Instant::now());
    assert_eq!(e.session.macro_wait(), Some(rev::macros::Wait::Layout));
    e.session
        .handle(key(KeyCode::Char('g'), KeyModifiers::CONTROL));
    settle(&mut e.session);
    assert_eq!(e.text(), source);
    assert_eq!(e.session.view().point, point);
    assert_eq!(e.session.buffer().unwrap().stamp(), stamp);
    assert_eq!(e.session.macro_stop().unwrap().reason, StopReason::Canceled);
    assert_eq!(e.session.macro_status(), Status::Idle);
    assert_eq!(e.session.remaining_input(Instant::now()), None);
}
