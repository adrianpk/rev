use super::*;
use rev::command::{BufferCommand, Split};
use rev::coordinates::Coordinates;

fn instruction(s: &mut Session, text: &str) {
    s.handle(Event::Paste(text.into()));
    s.handle(key(KeyCode::Enter));
}
fn proposal(s: &mut Session) {
    support::until(|| {
        tick(s);
        assert!(
            s.remaining_input(Instant::now()).is_some() || s.echo().contains("proposal ready"),
            "proposal outcome: {}",
            s.echo()
        );
        s.echo().contains("proposal ready")
    });
}
fn switch(s: &mut Session, name: &str) {
    s.execute(Command::Buffer(BufferCommand::Switch));
    instruction(s, name);
}

// M-x/colon explicitly offer replacement versus insertion. Acceptance preserves
// exact generated bytes, leaves disk alone and records one native undo/redo step.
#[test]
fn explicit_native_application() {
    let generated = "```rust\r\nfn café() {}\r\n```\r\n";
    for profile in ["non-modal", "modal"] {
        for (command, selection, prefix, suffix, output) in [
            ("ai-prompt", true, "", " selection\n", "replace"),
            ("ai-prompt", false, "", "é original selection\n", "insert"),
            ("ai-implement", true, "é original", " selection\n", "insert"),
        ] {
            let f = Fixture::new();
            let mut s = editor(&f, "normal", profile, selection);
            f.write("result", generated);
            let original = s.buffer().unwrap().stamp();
            let point = s.view().point;
            let config = fs::read(f.0.join("config.toml")).unwrap();
            named(&mut s, profile, command);
            assert!(!f.0.join("rpc-started").exists());
            let frame = s.frame().unwrap();
            assert!(
                frame
                    .rows()
                    .iter()
                    .any(|row| row.text().contains(&format!("AI {output}"))),
                "{command} {profile}"
            );
            instruction(&mut s, "Keep every code byte, including fences.");
            proposal(&mut s);
            assert!(s.buffer().unwrap().is_readonly());
            assert_eq!(
                fs::read_to_string(f.0.join("source.txt")).unwrap(),
                "é original selection\n"
            );
            let prompt: serde_json::Value =
                serde_json::from_str(&fs::read_to_string(f.0.join("prompt")).unwrap()).unwrap();
            assert_eq!(prompt["output"], output);
            assert_eq!(
                prompt["instruction"],
                "Keep every code byte, including fences."
            );
            if command == "ai-implement" {
                assert_eq!(prompt["observations"]["text"], "");
            }
            s.execute(Command::AiApplyResult);
            assert!(s.echo().contains("result applied"), "{}", s.echo());
            let expected = format!("{prefix}{generated}{suffix}");
            assert_eq!(text(&s), expected);
            assert_eq!(s.buffer().unwrap().id(), original.buffer);
            assert_eq!(s.buffer().unwrap().history().len(), 1);
            assert!(s.buffer().unwrap().is_modified());
            assert!(
                Coordinates::new(s.buffer().unwrap())
                    .unwrap()
                    .is_boundary(s.view().point.position)
                    .unwrap()
            );
            s.execute(Command::AiApplyResult);
            assert!(s.echo().contains("No AI result"));
            assert_eq!(text(&s), expected);
            s.execute(Command::History(History::Undo));
            assert_eq!(text(&s), "é original selection\n");
            assert_eq!(s.view().point.position, point.position);
            assert!(!s.buffer().unwrap().is_modified());
            s.execute(Command::History(History::Redo));
            assert_eq!(text(&s), expected);
            assert_eq!(
                fs::read_to_string(f.0.join("source.txt")).unwrap(),
                "é original selection\n"
            );
            assert_eq!(fs::read(f.0.join("config.toml")).unwrap(), config);
        }
    }
}

// One canonical transaction maps the visible peer and retained source view,
// including a generated combining mark that joins the preceding grapheme.
#[test]
fn shared_unicode_publication() {
    let f = Fixture::new();
    let mut s = editor(&f, "normal", "non-modal", true);
    f.write("result", "\u{301}👩‍💻\r\n");
    s.execute(Command::Split(Split::Below));
    let owner = s.windows().selected_id();
    let peer = s
        .windows()
        .order()
        .into_iter()
        .find(|id| *id != owner)
        .unwrap();
    s.select_view(peer).unwrap();
    s.execute(Command::Motion(Motion::BufferEnd));
    s.select_view(owner).unwrap();
    s.execute(Command::AiImplement);
    instruction(&mut s, "Insert exactly the generated text.");
    proposal(&mut s);
    s.execute(Command::AiApplyResult);
    assert!(s.echo().contains("result applied"), "{}", s.echo());
    assert_eq!(text(&s), "é original\u{301}👩‍💻\r\n selection\n");
    let buffer = s.buffer().unwrap();
    for (_, view) in s.windows().iter() {
        assert_eq!(view.point.stamp, buffer.stamp());
        assert!(
            Coordinates::new(buffer)
                .unwrap()
                .is_boundary(view.point.position)
                .unwrap()
        );
    }
    s.execute(Command::History(History::Undo));
    assert_eq!(text(&s), "é original selection\n");
    assert_eq!(s.view().point.position, Scalar(10));
    s.select_view(peer).unwrap();
    assert_eq!(s.view().point.position.0, s.buffer().unwrap().len_chars());
}

// Moving focus cannot retarget an insertion. A proposal arriving during another
// buffer's editing stays inspectable and applies only after explicit selection.
#[test]
fn focus_never_retargets() {
    let f = Fixture::new();
    let mut s = editor(&f, "settle_gate", "non-modal", false);
    f.write("result", "generated ");
    let source = s.buffer().unwrap().id();
    s.execute(Command::AiImplement);
    instruction(&mut s, "Generate for the captured source.");
    support::until(|| f.0.join("partial").exists());
    let other = f.write("other.txt", "unrelated");
    s.execute(Command::FindFile);
    instruction(&mut s, other.to_str().unwrap());
    let unrelated = s.buffer().unwrap().stamp();
    fs::write(f.0.join("release"), "").unwrap();
    proposal(&mut s);
    assert_eq!(s.buffer().unwrap().stamp(), unrelated);
    s.execute(Command::AiApplyResult);
    assert!(s.echo().contains("Select the AI result"));
    assert_eq!(text(&s), "unrelated");
    switch(&mut s, "*AI Result*");
    s.execute(Command::AiApplyResult);
    assert_eq!(s.buffer().unwrap().id(), source);
    assert_eq!(text(&s), "generated é original selection\n");
    switch(&mut s, "other.txt");
    assert_eq!(s.buffer().unwrap().stamp(), unrelated);
    assert_eq!(fs::read_to_string(other).unwrap(), "unrelated");
}

// Edits and reloads invalidate captured coordinates permanently, including an
// undo back to identical bytes. The rejected proposal remains read-only data.
#[test]
fn stale_sources_reject() {
    for change in ["local", "undo", "reload"] {
        let f = Fixture::new();
        let mut s = editor(&f, "settle_gate", "non-modal", true);
        s.execute(Command::AiPrompt);
        instruction(&mut s, "Replace the captured selection.");
        support::until(|| f.0.join("partial").exists());
        if change == "reload" {
            fs::write(f.0.join("source.txt"), "fresh external source\n").unwrap();
            support::until(|| {
                tick(&mut s);
                text(&s) == "fresh external source\n"
            });
        } else {
            s.insert('x');
            if change == "undo" {
                s.execute(Command::History(History::Undo));
            }
        }
        let expected = text(&s);
        let stamp = s.buffer().unwrap().stamp();
        fs::write(f.0.join("release"), "").unwrap();
        proposal(&mut s);
        assert_eq!(s.buffer().unwrap().stamp(), stamp);
        switch(&mut s, "*AI Result*");
        let observation = text(&s);
        s.execute(Command::AiApplyResult);
        assert!(s.echo().contains("stale"), "{change}: {}", s.echo());
        assert_eq!(text(&s), observation);
        s.execute(Command::AiDiscardResult);
        assert_eq!(text(&s), expected);
        assert_eq!(s.buffer().unwrap().stamp(), stamp);
    }
}

// Saving to a different path does not change the text revision, but it retires
// the captured association. A model cannot publish into the newly chosen file.
#[test]
fn association_change_rejects() {
    let f = Fixture::new();
    let mut s = editor(&f, "settle_gate", "non-modal", false);
    let stamp = s.buffer().unwrap().stamp();
    s.execute(Command::AiImplement);
    instruction(&mut s, "Generate at this point.");
    support::until(|| f.0.join("partial").exists());
    let target = f.0.join("saved-as.txt");
    s.execute(Command::WriteFile);
    instruction(&mut s, target.to_str().unwrap());
    assert_eq!(s.buffer().unwrap().stamp(), stamp);
    fs::write(f.0.join("release"), "").unwrap();
    proposal(&mut s);
    s.execute(Command::AiApplyResult);
    assert!(s.echo().contains("association changed"), "{}", s.echo());
    s.execute(Command::AiDiscardResult);
    assert_eq!(s.buffer().unwrap().file().unwrap().path(), target);
    assert_eq!(
        fs::read_to_string(target).unwrap(),
        "é original selection\n"
    );
}

// Instruction cancellation starts no process; result discard closes every
// shared result view. Explanations never gain an apply action from selection.
#[test]
fn discard_and_explanation() {
    for profile in ["non-modal", "modal"] {
        let f = Fixture::new();
        let mut s = editor(&f, "normal", profile, true);
        let original = s.buffer().unwrap().stamp();
        let point = s.view().point;
        named(&mut s, profile, "ai-prompt");
        s.handle(Event::Key(KeyEvent::new(
            KeyCode::Char('g'),
            KeyModifiers::CONTROL,
        )));
        assert!(!f.0.join("rpc-started").exists());
        assert_eq!(s.buffer().unwrap().stamp(), original);
        named(&mut s, profile, "ai-prompt");
        instruction(&mut s, "Generate a proposal.");
        proposal(&mut s);
        s.execute(Command::Split(Split::Below));
        s.execute(Command::AiDiscardResult);
        assert_eq!(s.buffer().unwrap().stamp(), original);
        assert_eq!(s.view().point.position, point.position);
        for (_, v) in s.windows().iter() {
            assert_eq!(v.point.stamp.buffer, original.buffer);
        }
        named(&mut s, profile, "ai-explain");
        ready(&mut s);
        s.execute(Command::AiApplyResult);
        assert!(s.echo().contains("no apply action"));
        assert!(s.buffer().unwrap().is_transient());
        named(&mut s, profile, "ai-discard-result");
        assert_eq!(s.buffer().unwrap().stamp(), original);
        assert_eq!(s.buffer().unwrap().history().len(), 0);
    }
}

// Before settlement there is no publication authority. Cancellation consumes
// even a late successful stream; malformed/oversized output cannot become edits.
#[test]
fn incomplete_results_never_apply() {
    for mode in ["late_cancel", "invalid", "oversize"] {
        let f = Fixture::new();
        let mut s = editor(&f, mode, "non-modal", true);
        if mode == "oversize" {
            f.write(
                "config.toml",
                &format!(
                    "[ai.pi]\ncommand='{}'\nmax_result_bytes=1\n",
                    f.0.join("pi-peer").display()
                ),
            );
            // Use the actual startup policy; configuration is not hot reloaded.
            let startup = rev::config::prepare(&f.0.join("config.toml"));
            let mut buffers = Buffers::with_settings(startup.snapshot).unwrap();
            let id = buffers.visit(&f.0.join("source.txt")).unwrap();
            let b = buffers.get_mut(id).unwrap();
            let mut v = View::new(b);
            b.activate_mark(v.point).unwrap();
            v.point.position = Scalar(10);
            s = Session::new(
                buffers,
                v,
                Size {
                    width: 100,
                    height: 28,
                },
            )
            .unwrap();
        }
        let original = s.buffer().unwrap().stamp();
        s.execute(Command::AiPrompt);
        instruction(&mut s, "Generate a bounded proposal.");
        if mode == "late_cancel" {
            support::until(|| f.0.join("prompt").exists());
            s.execute(Command::AiApplyResult);
            assert!(s.echo().contains("No AI result"));
            s.execute(Command::AiDiscardResult);
        }
        support::until(|| {
            tick(&mut s);
            s.remaining_input(Instant::now()).is_none()
        });
        assert_eq!(s.buffer().unwrap().stamp(), original);
        assert_eq!(s.buffer().unwrap().history().len(), 0);
        s.execute(Command::AiApplyResult);
        assert!(s.echo().contains("No AI result"));
    }
}

// Capturing precedes instruction input. An automatic reload during that prompt
// invalidates submission before even the Pi version process can be launched.
#[test]
fn prompt_rechecks_source() {
    let f = Fixture::new();
    let mut s = editor(&f, "normal", "non-modal", true);
    s.execute(Command::AiPrompt);
    fs::write(f.0.join("source.txt"), "external during prompt\n").unwrap();
    support::until(|| {
        tick(&mut s);
        text(&s) == "external during prompt\n"
    });
    let current = s.buffer().unwrap().stamp();
    instruction(&mut s, "Replace the originally captured range.");
    assert!(s.echo().contains("stale"), "{}", s.echo());
    assert!(!f.0.join("version-pid").exists());
    assert_eq!(s.buffer().unwrap().stamp(), current);
}

// A closed source cannot be reopened or substituted by an eventual proposal.
// Discard safely closes that result without leaving a view bound to dead text.
#[test]
fn closed_source_rejects() {
    let f = Fixture::new();
    let mut s = editor(&f, "settle_gate", "non-modal", true);
    let source = s.buffer().unwrap().id();
    s.execute(Command::AiPrompt);
    instruction(&mut s, "Generate for this source.");
    support::until(|| f.0.join("partial").exists());
    s.execute(Command::Buffer(BufferCommand::Kill));
    instruction(&mut s, "source.txt");
    fs::write(f.0.join("release"), "").unwrap();
    proposal(&mut s);
    switch(&mut s, "*AI Result*");
    s.execute(Command::AiApplyResult);
    assert!(s.echo().contains("not live"), "{}", s.echo());
    s.execute(Command::AiDiscardResult);
    assert_ne!(s.buffer().unwrap().id(), source);
    s.frame().unwrap();
    assert_eq!(
        fs::read_to_string(f.0.join("source.txt")).unwrap(),
        "é original selection\n"
    );
}

// Missing instructions and read-only editing targets fail before external IO;
// the existing explanation command still owns its separate read-only behavior.
#[test]
fn editing_admission() {
    for command in [Command::AiPrompt, Command::AiImplement] {
        let f = Fixture::new();
        let mut s = editor(&f, "readonly", "non-modal", true);
        s.execute(command);
        assert!(s.echo().contains("read-only"), "{}", s.echo());
        assert!(!f.0.join("version-pid").exists());
    }
    let f = Fixture::new();
    let mut s = editor(&f, "normal", "non-modal", true);
    s.execute(Command::AiPrompt);
    instruction(&mut s, "");
    assert!(s.echo().contains("instruction must contain"));
    assert!(!f.0.join("version-pid").exists());
}
